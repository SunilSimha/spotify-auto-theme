#!/usr/bin/env python3
"""Build a light/dark CSS snippet for Spicetify from a theme's color.ini.

The snippet sets one colour scheme when the system is in light mode and another
when it is in dark mode. By default the schemes are read from the Catppuccin
Spicetify theme (frappe, latte, macchiato, mocha).

Usage:
    make-snippet.py LIGHT DARK [-o OUT.css] [--ini PATH_OR_URL]
    make-snippet.py --list [--ini PATH_OR_URL]

Examples:
    make-snippet.py latte mocha -o catppuccin-auto-scheme.css
    make-snippet.py latte frappe > my-snippet.css
    make-snippet.py Light Dark --ini ~/.config/spicetify/Themes/MyTheme/color.ini
"""
import argparse
import configparser
import re
import sys
import urllib.request

DEFAULT_INI = "https://raw.githubusercontent.com/catppuccin/spicetify/main/catppuccin/color.ini"

HEX = re.compile(r"^[0-9a-f]{6}$")
KEY = re.compile(r"^[a-z0-9_-]+$")


def load(source):
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source, timeout=30) as response:
            text = response.read().decode("utf-8")
    else:
        with open(source, encoding="utf-8") as fh:
            text = fh.read()
    parser = configparser.ConfigParser()
    parser.read_string(text)
    return parser


def block(parser, scheme):
    if scheme not in parser:
        sys.exit(f"no scheme {scheme!r}; available: {', '.join(parser.sections())}")
    lines = []
    for key, value in parser[scheme].items():
        key, value = key.strip(), value.strip().lstrip("#").lower()
        if not KEY.match(key) or not HEX.match(value):
            sys.exit(f"unexpected entry in [{scheme}]: {key!r} = {value!r}")
        r, g, b = (int(value[i:i + 2], 16) for i in (0, 2, 4))
        lines.append(f"    --spice-{key}: #{value};")
        lines.append(f"    --spice-rgb-{key}: {r},{g},{b};")
    return "\n".join(lines)


def main():
    args = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    args.add_argument("light", nargs="?", help="scheme to use when the system is light")
    args.add_argument("dark", nargs="?", help="scheme to use when the system is dark")
    args.add_argument("-o", "--output", help="write the CSS here instead of stdout")
    args.add_argument("--ini", default=DEFAULT_INI, help="color.ini path or URL")
    args.add_argument("--list", action="store_true", help="list the schemes in the ini")
    opts = args.parse_args()

    parser = load(opts.ini)
    if opts.list:
        print("\n".join(parser.sections()))
        return
    if not (opts.light and opts.dark):
        args.error("give a LIGHT and a DARK scheme, or --list")

    css = f"""/* Auto light/dark colour scheme for Spicetify (Marketplace snippet).
 * System light -> {opts.light}, system dark -> {opts.dark}.
 * Generated by make-snippet.py from {opts.ini}
 * Each colour is set twice: --spice-<name> (hex) and --spice-rgb-<name> (r,g,b). */
@media (prefers-color-scheme: light) {{
  :root:root {{
{block(parser, opts.light)}
  }}
}}
@media (prefers-color-scheme: dark) {{
  :root:root {{
{block(parser, opts.dark)}
  }}
}}
"""
    if opts.output:
        with open(opts.output, "w", encoding="utf-8") as fh:
            fh.write(css)
    else:
        sys.stdout.write(css)


if __name__ == "__main__":
    main()
